"""ZeroDOM vs Playwright MCP's page snapshot, per site, as a markdown table.

    uv run benchmarks/compare_mcp.py [sites.txt]   # default: benchmarks/sites.txt

Baseline is `page.aria_snapshot(mode="ai")` — the snapshot Playwright MCP sends a
model. Per site: tokens (tiktoken cl100k_base) for that snapshot vs
`to_compact_text()`, and the % of ZeroDOM selectors that resolve to exactly one
element in the live document. Writes benchmarks/RESULTS.md.
"""

from __future__ import annotations

import pathlib
import sys

from playwright.sync_api import sync_playwright

from zerodom.cli import count_tokens
from zerodom.parser import ZeroDOMParser

HERE = pathlib.Path(__file__).parent


def resolves(page, sel: str) -> int:
    # Playwright's engine, not querySelectorAll: selectors can carry `>>` (nth,
    # shadow scoping) and that engine pierces open shadow roots — what an agent hits.
    try:
        return page.locator(sel).count()
    except Exception:
        return -1  # invalid


def measure(page, url: str) -> tuple[int, int, int, int]:
    page.goto(url, wait_until="domcontentloaded", timeout=45_000)
    page.wait_for_timeout(1500)  # let the app shell settle
    aria = count_tokens(page.aria_snapshot(mode="ai"))
    graph = ZeroDOMParser(page.content(), url).parse()
    counts = [resolves(page, sel) for sel in graph.selector_map().values()]
    return aria, count_tokens(graph.to_compact_text()), counts.count(1), len(counts)


def main(argv: list[str]) -> int:
    src = pathlib.Path(argv[0]) if argv else HERE / "sites.txt"
    urls = [l.strip() for l in src.read_text().splitlines() if l.strip() and not l.startswith("#")]
    rows = ["| site | Playwright MCP snapshot | ZeroDOM | saved | unique selectors |",
            "|---|---:|---:|---:|---:|"]
    with sync_playwright() as p:
        browser = p.chromium.launch()
        for url in urls:
            page = browser.new_page()
            try:
                aria, zd, uniq, n = measure(page, url)
            except Exception as exc:  # a bot wall shouldn't kill the whole run
                rows.append(f"| {url} | — | — | — | {type(exc).__name__} |")
            else:
                saved = f"{1 - zd / aria:.1%}" if aria else "—"
                pct = f"{uniq / n:.1%} ({uniq}/{n})" if n else "—"
                rows.append(f"| {url} | {aria:,} | {zd:,} | {saved} | {pct} |")
            finally:
                page.close()
            print(rows[-1], flush=True)
        browser.close()
    out = HERE / "RESULTS.md"
    out.write_text("# ZeroDOM vs Playwright MCP snapshot\n\n"
                   "Generated by `uv run benchmarks/compare_mcp.py`. Tokens: tiktoken cl100k_base.\n\n"
                   + "\n".join(rows) + "\n")
    print(f"\nwrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
